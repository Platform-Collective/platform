export const brandingId = 'branding' as Plugin

/**
 * Options for producing a PDF of a document with a template applied.
 * @public
 */
export interface ComposeDocumentOptions {
  // Values entered in the print preview, override resolved document fields
  values?: FieldValues
  // Edited text of editable template elements, keyed by element id
  overrides?: Record<string, string>
  // Existing PDF or Word blob to use as document body instead of rendering the document
  file?: string
  // Content type of the body file, defaults to PDF
  fileContentType?: string
  // Document content laid out in the print preview (with page breaks), used as document body
  contentHtml?: string
  // Print the document page as displayed in the application, even for files
  usePage?: boolean
}

/** @public */
export type ComposeDocumentFn = (
  doc: Doc,
  template: Ref<PrintTemplate>,
  options?: ComposeDocumentOptions
) => Promise<string>


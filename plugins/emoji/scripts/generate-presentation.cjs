// Run from plugins/emoji after updating emojibase-data. No dataset is imported by renderers.
const { writeFileSync } = require('node:fs')
const { join } = require('node:path')
const unicodeEmoji = require('emojibase-data/meta/unicode.json')
const { version } = require('emojibase-data/package.json')

const qualified = new Map()
for (const emoji of unicodeEmoji) {
  if (!emoji.includes('\uFE0F')) continue
  const key = emoji.replace(/\uFE0F/g, '')
  if (emoji.length > (qualified.get(key)?.length ?? 0)) qualified.set(key, emoji)
}

// Factor exact sequences by their first ZWJ. Suffixes sharing a prefix list form one group.
const prefixesBySuffix = new Map()
for (const emoji of qualified.values()) {
  const index = emoji.indexOf('\u200D')
  const prefix = index < 0 ? emoji : emoji.slice(0, index)
  const suffix = index < 0 ? '' : emoji.slice(index)
  if (!prefixesBySuffix.has(suffix)) prefixesBySuffix.set(suffix, [])
  prefixesBySuffix.get(suffix).push(prefix)
}
const groups = new Map()
for (const [suffix, prefixes] of prefixesBySuffix) {
  const key = prefixes.sort().join(' ')
  if (!groups.has(key)) groups.set(key, [])
  groups.get(key).push(suffix)
}

const rows = [...groups].map(([prefixes, suffixes]) =>
  `  [${JSON.stringify(prefixes)}, ${JSON.stringify(suffixes)}]`
)
writeFileSync(join(__dirname, '../src/presentation-data.ts'), `// SPDX-License-Identifier: EPL-2.0

// Generated by scripts/generate-presentation.cjs from emojibase-data ${version}.
// Only FE0F-qualified sequences, factored into exact prefix/suffix combinations.
export const emojiPresentationGroups: Array<[string, string[]]> = [
${rows.join(',\n')}
]
`)

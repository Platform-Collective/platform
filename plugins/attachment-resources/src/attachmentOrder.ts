import type { Attachment } from '@hcengineering/attachment'

/**
 * Sorts attachments in the order they were added: by createdOn, then by _id
 * (ids generated by one client increase monotonically).
 * Returns a new array; the input is left untouched.
 */
export function sortAttachments<T extends Pick<Attachment, '_id' | 'createdOn'>> (attachments: T[]): T[] {
  return [...attachments].sort((a, b) => {
    const byCreated = (a.createdOn ?? 0) - (b.createdOn ?? 0)
    if (byCreated !== 0) return byCreated
    return a._id < b._id ? -1 : a._id > b._id ? 1 : 0
  })
}
